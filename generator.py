def generate_scenario(player_count: int) -> dict:
    disaster_data = random.choice(DISASTERS)
    shelter = random.choice(SHELTERS)
    survivors_needed = max(2, player_count // 2)
    return {
        "disaster": disaster_data["disaster"],
        "threat": disaster_data["threat"],
        "shelter": shelter,
        "survivors_needed": survivors_needed,
    }


def generate_cards_for_players(player_names: list, scenario: dict) -> dict:
    result = {}
    used_professions = []
    used_specials = []
    for name in player_names:
        available_profs = [p for p in PROFESSIONS if p not in used_professions]
        if not available_profs:
            available_profs = PROFESSIONS
        profession = random.choice(available_profs)
        used_professions.append(profession)

        available_specials = [s for s in SPECIALS if s not in used_specials]
        if not available_specials:
            available_specials = SPECIALS
        special = random.choice(available_specials)
        used_specials.append(special)

        result[name] = {
            "profession": profession,
            "hobby": random.choice(HOBBIES),
            "luggage": random.choice(LUGGAGE),
            "age": str(random.randint(18, 72)),
            "health": random.choice(HEALTH),
            "biology": random.choice(BIOLOGY),
            "fact": random.choice(FACTS),
            "special": special,
        }
    return result
